// gen-actions-docs.mjs — the registry's generated DOCS (contract V2-1.11 §4 decision 1, §5.7 rule 6;
// V2-2.4b): pure functions from the generated actions.manifest.json (+ schema/formats.ts rows) to
//
//   studioActionsSkill   plugins/design/skills/studio-actions/SKILL.md — per capability, the file
//                        to edit or the verb to run (S12's skill index)
//   designHelpBlock      the generated block inside plugins/design/commands/help.md (/design:help)
//   cliHelpModule        cli/lib/design-help.gen.mjs — the verb tiers `maude design help` prints
//   aiActionsDoc         the public docs page (site/content/docs/ai-actions.mdx — Phase 7 owns the
//                        site; gen-actions prints it with --print-docs) incl. §5.5's paste-in allow list
//
// scripts/gen-actions.mjs writes them and its --check fails on drift. No I/O here.

const cell = (s) =>
  String(s ?? '')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ');
const code = (s) => (s ? `\`${String(s).replaceAll('`', "'")}\`` : '');
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');

const agentOf = (a) => (a.agent?.path === 'pending' ? a.agent.want : a.agent);
const byLabel = (x, y) =>
  String(x.label).localeCompare(String(y.label)) || x.id.localeCompare(y.id);

/** The actions that need an AI path (§5.1: kind !== 'place'), split by path. */
function groups(m) {
  const rows = m.actions.filter((a) => a.kind !== 'place' && a.agent);
  const of = (p) => rows.filter((a) => a.agent.path === p).sort(byLabel);
  return {
    file: of('file'),
    cli: of('cli'),
    human: of('human'),
    pending: of('pending'),
    all: rows,
  };
}

const tierOf = (m) => new Map(m.verbs.map((v) => [v.verb, v]));
/** `maude design export --out x` → the manifest verb key (`design export`). */
function verbKey(m, verb) {
  const words = String(verb)
    .replace(/^maude /, '')
    .split(' ');
  const tiers = tierOf(m);
  for (const n of [3, 2, 1]) {
    const k = words.slice(0, n).join(' ');
    if (tiers.has(k)) return k;
  }
  return null;
}

function verbsByTier(m) {
  const out = { auto: [], prompt: [], human: [] };
  for (const v of m.verbs) {
    out[v.tier] ??= [];
    out[v.tier].push(v);
  }
  return out;
}

const formatsTable = (formats) =>
  table(
    ['Format', 'Files', 'Schema', 'Strict check', 'Skill'],
    formats.map((f) => [code(f.format), f.files, code(f.schema), f.check, code(f.skill)])
  );

export function studioActionsSkill(m, formats) {
  const g = groups(m);
  const tiers = tierOf(m);
  const t = verbsByTier(m);
  const fmt = new Map(formats.map((f) => [f.format, f]));
  return `---
name: studio-actions
description: "Look up any Maude studio capability: the file to edit or the maude verb to run, its permission tier, and the skill that teaches it."
---

<!-- GENERATED by scripts/gen-actions.mjs from apps/studio/actions/, actions/verbs.ts and schema/formats.ts — do not edit by hand. manifest ${m.manifestVersion} -->

# studio-actions

Follow [host conventions](../../HARNESS.md) for Claude Code or Codex.

Every capability in the Maude studio has exactly one AI path (contract V2-1.11 §5.1). Find it below, then:

- **file**: edit that file. Use \`Edit\` on existing canvases, never a whole-file \`Write\`. Hooks run \`maude design check --strict\` on every write and restore the file on an error. Read the named skill first, because it teaches the format.
- **verb**: run the \`maude\` verb. \`auto\` verbs run without a prompt in the Maude chat. \`prompt\` verbs show the person a permission card.
- **person**: only the person does this. Tell them where it is. Never script it, and no verb is designed for it.
- **not yet**: the AI path lands with the package named. Until then, say it can't be done from here yet.

Validate a file yourself with \`maude design check <file> --strict [--against <before>]\`.

## Formats you edit (${formats.length})

${formatsTable(formats)}

## Capabilities

${g.all.length} capabilities: ${g.file.length} by file, ${g.cli.length} by verb, ${g.human.length} the person's only, ${g.pending.length} not yet.

### Edit a file (${g.file.length})

${table(
  ['Capability', 'Action id', 'Format', 'How', 'Skill'],
  g.file.map((a) => [
    a.label,
    code(a.id),
    code(a.agent.format),
    a.agent.how,
    code(a.agent.skill ?? fmt.get(a.agent.format)?.skill),
  ])
)}

### Run a verb (${g.cli.length})

${table(
  ['Capability', 'Action id', 'Verb', 'Tier'],
  g.cli.map((a) => {
    const k = verbKey(m, a.agent.verb);
    return [a.label, code(a.id), code(a.agent.verb), k ? tiers.get(k).tier : '?'];
  })
)}

### Only the person (${g.human.length})

${table(
  ['Capability', 'Action id', 'Why'],
  g.human.map((a) => [
    a.label,
    code(a.id),
    `${a.agent.because}${a.agent.note ? ` — ${a.agent.note}` : ''}`,
  ])
)}

### Not yet (${g.pending.length})

${table(
  ['Capability', 'Action id', 'Package', 'Will be'],
  g.pending.map((a) => {
    const w = agentOf(a);
    return [
      a.label,
      code(a.id),
      a.agent.package,
      w?.path === 'cli' ? code(w.verb) : (w?.path ?? ''),
    ];
  })
)}

## Verbs by permission tier

The tier belongs to the verb's name, and no flag raises it (§5.3). \`auto\` covers effect \`none\` or \`project\`. Anything else shows the permission card. \`human\` verbs are for people in a terminal.

${table(
  ['Verb', 'Effect', 'Tier', 'Note'],
  [...t.auto, ...t.prompt, ...t.human].map((v) => [
    code(`maude ${v.verb}`),
    v.effect,
    v.tier,
    v.hold ?? '',
  ])
)}
`;
}

export const HELP_BEGIN = '<!-- BEGIN GENERATED: studio capabilities (scripts/gen-actions.mjs) -->';
export const HELP_END = '<!-- END GENERATED: studio capabilities -->';

export function designHelpBlock(m) {
  const g = groups(m);
  const t = verbsByTier(m);
  const list = (vs) =>
    vs
      .filter((v) => v.scope === 'design')
      .map((v) => v.verb.replace(/^design /, ''))
      .join(' · ');
  return `${HELP_BEGIN}
## Studio capabilities

Every studio action has one AI path: ${g.file.length} by editing a file, ${g.cli.length} by a \`maude\` verb, ${g.human.length} only the person can do, ${g.pending.length} not yet. The \`studio-actions\` skill has the full index, with the file or verb for each.

| Tier | \`maude design\` verbs |
| --- | --- |
| auto (no prompt in the Maude chat) | ${list(t.auto)} |
| prompt (permission card) | ${list(t.prompt)} |
| person only | ${list(t.human)} |
${HELP_END}`;
}

/** Replace the generated block in help.md (appended once if the markers are missing). */
export function withHelpBlock(helpMd, block) {
  const a = helpMd.indexOf(HELP_BEGIN);
  const b = helpMd.indexOf(HELP_END);
  if (a === -1 || b === -1) return `${helpMd.replace(/\n*$/, '\n')}\n${block}\n`;
  return `${helpMd.slice(0, a)}${block}${helpMd.slice(b + HELP_END.length)}`;
}

export function cliHelpModule(m) {
  const t = verbsByTier(m);
  const wrap = (words) => {
    const lines = [];
    let cur = '';
    for (const w of words) {
      if (cur && `${cur} · ${w}`.length > 84) {
        lines.push(cur);
        cur = w;
      } else cur = cur ? `${cur} · ${w}` : w;
    }
    if (cur) lines.push(cur);
    return lines.map((l) => `            ${l}`).join('\n');
  };
  const names = (vs) =>
    vs.filter((v) => v.scope === 'design').map((v) => v.verb.replace(/^design /, ''));
  const text = `Verbs by permission tier (generated from actions.manifest.json, contract V2-1.11 §5.3):
  auto    No prompt in the Maude chat (effect none/project):
${wrap(names(t.auto))}
  prompt  Shows the permission card:
${wrap(names(t.prompt))}
  human   For people in a terminal. Never in the AI allow list:
${wrap(names(t.human))}
  Every studio capability's file or verb: the design plugin's studio-actions skill.
`;
  return `// GENERATED by scripts/gen-actions.mjs from apps/studio/actions/verbs.ts — DO NOT EDIT BY HAND.
// What \`maude design help\` prints under the static usage (contract V2-1.11 §5.7 rule 6).
// manifest ${m.manifestVersion}

export const DESIGN_VERB_TIERS_HELP = ${JSON.stringify(text)};

/** The \`maude design\` verbs the manifest knows, by tier. */
export const DESIGN_VERBS_BY_TIER = ${JSON.stringify({
    auto: names(t.auto),
    prompt: names(t.prompt),
    human: names(t.human),
  })};
`;
}

/** `autoRules` = actions/verbs.ts autoAllowRules() — the Maude chat's generated allow list (§5.5). */
