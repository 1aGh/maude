#!/usr/bin/env node
// Token pipeline (V2-2.6, T13 minimum) — every token copy the product ships is GENERATED from a
// design system's colors_and_type.css; nothing is typed by hand.
//
//   node scripts/gen-tokens.mjs           write every output
//   node scripts/gen-tokens.mjs --check   exit 1 on drift (part of the `tokens` quality gate)
//
// 1. apps/studio/client/styles/1-tokens-maude-v2.css — the maude-v2 ladder for the studio client,
//    scoped to `.maude-v2[data-theme]` ONLY: every `:root` is dropped from the source's selector
//    lists, so the v1 shell (which never carries `.maude-v2`) is untouched until Phase 4 mounts the
//    v2 chrome under that wrapper.
// 2. apps/studio/canvas-hud-tokens.gen.ts — the canvas iframe's HUD/chrome block
//    (`--maude-hud-*`, `--maude-chrome-*`) that canvas-shell.tsx injects. Filled from HUD_SOURCE_DS
//    through HUD_TEMPLATE below; `maude` today (byte-identical to the block it replaces), switched
//    to `maude-v2` by the Phase 4 shell work — change the constant and the name map, regenerate.
// (The site's copy, site/app/mdcc-tokens.css, has its own generator: site/scripts/sync-mdcc-tokens.mjs.)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
// The schema scope selector (`.ds[data-theme="t"]`, V2-1.13 §5.3.12) sits on its own line right after each
// `.<rootClass>[data-theme]`; it scopes canvases, never the studio client, so it is dropped here.
const DS_SCOPE = /,\n[ \t]*\.ds\[data-theme="[a-z0-9-]+"\]/g;
const ds = (name) =>
  readFileSync(join(ROOT, `.design/system/${name}/colors_and_type.css`), 'utf8').replace(
    DS_SCOPE,
    ''
  );

// ── 1 · maude-v2 → client, scoped ────────────────────────────────────────────────────────────
const V2_OUT = 'apps/studio/client/styles/1-tokens-maude-v2.css';
function scopedV2() {
  const src = ds('maude-v2');
  const lines = src.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^\s*:root\s*\{/.test(l))
      throw new Error(
        'maude-v2 declares a bare `:root {` block — it cannot be scoped; add a .maude-v2 selector'
      );
    if (/^\s*:root,\s*$/.test(l)) {
      if (!/^\s*\.maude-v2\[data-theme="(light|dark)"\]/.test(lines[i + 1] ?? ''))
        throw new Error(
          `maude-v2 line ${i + 1}: \`:root,\` is not followed by a .maude-v2 selector`
        );
      continue; // drop :root from this selector list
    }
    out.push(l);
  }
  const body = out.join('\n').trim();
  return `/* GENERATED by scripts/gen-tokens.mjs from .design/system/maude-v2/colors_and_type.css
 * — DO NOT EDIT BY HAND. Run: node scripts/gen-tokens.mjs
 * Scoped to .maude-v2[data-theme] only (every :root dropped), so the v1 shell is untouched until
 * the v2 chrome mounts under that wrapper (Phase 4). */

@layer tokens {
${body
  .split('\n')
  .map((l) => (l ? `  ${l}` : l))
  .join('\n')}
}
`;
}

// ── 1b · maude-v2 → the shell scope, ADDITIVE ONLY ───────────────────────────────────────────
// Gate-B polish (decision:maude/v2-gate-b-polish1-v2-tokens-additive-in-shell): a v2 sheet or panel that
// mounts under `.maude` but outside `.maude-v2` (the Export / Share / Handoff sheets, the Exports panel,
// ⌘K's empty block, every v2 component inside `.st-shell`) asked for --scrim, --island-*, --w-*,
// --font-rounded … and got nothing. This block declares, on `.maude[data-theme]`, exactly the maude-v2
// names the shell ladder (1-tokens.css + 1-tokens-maude.css) does NOT declare — it never overrides a
// shell value, so the v1 ladder (spacing 4px steps, radii, Inter) and every v1 surface stay as they are.
// A name later added to the shell by hand drops out of this file on the next run (the --check gate).
const V2_SHELL_OUT = 'apps/studio/client/styles/1-tokens-maude-v2-shell.css';
const SHELL_TOKEN_SOURCES = [
  'apps/studio/client/styles/1-tokens.css',
  'apps/studio/client/styles/1-tokens-maude.css',
];
// The shell's accent is still the v1 indigo (1-tokens-maude.css), so a v2 token that is a literal of the
// v2 azure would be a second accent hue in the shell; these follow the shell's own --accent instead, in the
// same relation the v2 file states (`--accent-muted: var(--accent-soft)`, focus = accent, selection = accent
// at 22 % / 30 %).
// The island material in the shell is SOLID (V2-1.8 M1–M3, floating-panels.css): --island-bg is the panel surface,
// never the v2 translucent glass, and nothing blurs.
const SHELL_ACCENT_DERIVED = {
  '--x-island-bg': 'var(--bg-1)',
  '--x-island-bg-strong': 'var(--bg-1)',
  '--accent-soft': 'var(--accent-muted)',
  '--focus-ring': 'var(--accent)',
  '--selection': {
    light: 'color-mix(in oklch, var(--accent) 22%, transparent)',
    dark: 'color-mix(in oklch, var(--accent) 30%, transparent)',
  },
};
function shellAdditiveV2() {
  const shellNames = new Set();
  for (const rel of SHELL_TOKEN_SOURCES)
    for (const m of readFileSync(join(ROOT, rel), 'utf8').matchAll(/^\s*(--[a-z0-9-]+)\s*:/gm))
      shellNames.add(m[1]);
  const src = scopedV2()
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((l) => l.replace(/\s+$/, ''));
  const out = [];
  let kept = 0;
  let theme = null;
  for (const l of src) {
    const decl = /^(\s*)(--[a-z0-9-]+)\s*:/.exec(l);
    if (decl) {
      if (shellNames.has(decl[2])) continue;
      const derived = SHELL_ACCENT_DERIVED[decl[2]];
      const v = typeof derived === 'object' ? derived[theme] : derived;
      out.push(v ? `${decl[1]}${decl[2]}: ${v};` : l);
      kept++;
      continue;
    }
    if (/^\s*[a-z-]+\s*:[^{]*;\s*$/.test(l)) continue; // a plain property (color-scheme): the shell owns it
    if (!l.trim()) continue;
    if (/data-theme="(light|dark)"\]\s*\{/.test(l))
      theme = l.includes('"light"') ? 'light' : 'dark';
    out.push(l.replace(/\.maude-v2\[data-theme=/g, '.maude[data-theme='));
  }
  // drop selector blocks the filter emptied (a selector list followed directly by its closing brace)
  const text = out.join('\n').replace(/\n(?:[ \t]*[^\n{};]+,\n)*[ \t]*[^\n{};]+\{\n[ \t]*\}/g, '');
  if (!kept) throw new Error('maude-v2: no v2-only token left for the shell scope');
  return `/* GENERATED by scripts/gen-tokens.mjs from .design/system/maude-v2/colors_and_type.css
 * — DO NOT EDIT BY HAND. Run: node scripts/gen-tokens.mjs
 * ADDITIVE: only the maude-v2 tokens the shell ladder (1-tokens.css, 1-tokens-maude.css) leaves undefined,
 * declared on .maude[data-theme], so a v2 surface mounted in the shell resolves them. Never overrides a
 * shell token. */
${text}
`;
}

// ── 2 · HUD block for the canvas iframe ──────────────────────────────────────────────────────
const HUD_OUT = 'apps/studio/canvas-hud-tokens.gen.ts';
const HUD_SOURCE_DS = 'maude';
// Theme blocks of the source DS: the selector line that opens each block.
const HUD_BLOCKS = { dark: '.maude[data-theme="dark"] {', light: '.maude[data-theme="light"] {' };
// {dark:name} / {light:name} = that DS token's value in that theme's block.
// S2.8 (DDR-046 rename): the guide colour — smart guides, spacing chips, the preset ruler's edge line — is ONE fixed
// magenta in both themes, owned by maude-v2 (`--x-guide` / `--x-guide-fg`). It is not a theme token, so it is read from
// that system whatever HUD_SOURCE_DS is, and declared once on `:root` (the light block inherits it).
const HUD_GUIDE_DS = 'maude-v2';
const HUD_TEMPLATE = `
:root,
:root[data-maude-theme="dark"] {
  --guide:    {guide:x-guide};
  --guide-fg: {guide:x-guide-fg};
  /* the v1 name of --guide (DDR-046); an old canvas that still says var(--guide-magenta) keeps its colour */
  --guide-magenta: var(--guide);

  --maude-hud-accent:        {dark:accent};
  --maude-hud-accent-hover:  {dark:accent-hover};
  --maude-hud-accent-active: {dark:accent-active};
  --maude-hud-accent-fg:     {dark:accent-fg};
  --maude-hud-accent-tint:   color-mix(in oklab, {dark:accent} 16%, transparent);

  --maude-chrome-bg-0:      {dark:bg-0};
  --maude-chrome-bg-1:      {dark:bg-1};
  --maude-chrome-bg-2:      {dark:bg-2};
  --maude-chrome-fg-0:      {dark:fg-0};
  --maude-chrome-fg-1:      {dark:fg-1};
  --maude-chrome-border:    {dark:border-subtle};
  --maude-chrome-dot:       {dark:canvas-dot};
  --maude-chrome-shadow:    rgba(0, 0, 0, 0.46);
  --maude-chrome-font-mono: 'JetBrains Mono', 'Geist Mono', ui-monospace, 'SF Mono', Menlo, monospace;
  /* gate-a-polish: the menu / label chrome speaks the body face (mono only in Advanced + code, README) */
  --maude-chrome-font-body: 'Inter', system-ui, -apple-system, 'Segoe UI', sans-serif;
  --maude-chrome-error:     {dark:status-error-text};
}
:root[data-maude-theme="light"] {
  --maude-hud-accent:        {light:accent};
  --maude-hud-accent-hover:  {light:accent-hover};
  --maude-hud-accent-active: {light:accent-active};
  --maude-hud-accent-fg:     {light:accent-fg};
  --maude-hud-accent-tint:   color-mix(in oklab, {light:accent} 12%, transparent);

  --maude-chrome-bg-0:   {light:bg-0};
  --maude-chrome-bg-1:   {light:bg-1};
  --maude-chrome-bg-2:   {light:bg-2};
  --maude-chrome-fg-0:   {light:fg-0};
  --maude-chrome-fg-1:   {light:fg-1};
  --maude-chrome-border: {light:border-subtle};
  --maude-chrome-dot:    {light:canvas-dot};
  --maude-chrome-shadow: color-mix(in oklab, {light:fg-0} 14%, transparent);
  --maude-chrome-error:  {light:status-error-text};
}
`;

function blockOf(src, opener) {
  const at = src.indexOf(opener);
  if (at < 0) throw new Error(`${HUD_SOURCE_DS}: block "${opener}" not found`);
  return src.slice(at, src.indexOf('\n}', at));
}
function hudCss() {
  const src = ds(HUD_SOURCE_DS);
  const blocks = Object.fromEntries(
    Object.entries(HUD_BLOCKS).map(([t, o]) => [t, blockOf(src, o)])
  );
  // The HUD block is a literal snapshot (the canvas iframe may host another system), so a value
  // that is exactly `var(--other)` in the same block — a schema-v1 alias such as
  // `--canvas-dot: var(--x-canvas-dot)` — is followed to its declared value.
  const lookup = (theme, name, depth = 0) => {
    const m = blocks[theme].match(new RegExp(`^\\s*--${name}:\\s*([^;]+);`, 'm'));
    if (!m) throw new Error(`${HUD_SOURCE_DS} ${theme}: no --${name}`);
    const v = m[1].trim();
    const ref = /^var\(--([a-z0-9-]+)\)$/.exec(v);
    return ref && depth < 8 && new RegExp(`^\\s*--${ref[1]}:`, 'm').test(blocks[theme])
      ? lookup(theme, ref[1], depth + 1)
      : v;
  };
  const guide = (name) => {
    const m = ds(HUD_GUIDE_DS).match(new RegExp(`^\\s*--${name}:\\s*([^;]+);`, 'm'));
    if (!m) throw new Error(`${HUD_GUIDE_DS}: no --${name}`);
    return m[1].trim();
  };
  return HUD_TEMPLATE.replace(/\{guide:([a-z0-9-]+)\}/g, (_, name) => guide(name)).replace(
    /\{(dark|light):([a-z0-9-]+)\}/g,
    (_, theme, name) => lookup(theme, name)
  );
}
function hudModule() {
  return `// GENERATED by scripts/gen-tokens.mjs from .design/system/${HUD_SOURCE_DS}/colors_and_type.css
// — DO NOT EDIT BY HAND. Run: node scripts/gen-tokens.mjs
// The canvas iframe's HUD/chrome token block (--maude-hud-*, --maude-chrome-*), injected by
// canvas-shell.tsx. See the comment above its import there for why the HUD owns its own family.
export const HUD_TOKENS_CSS = \`${hudCss()}\`;
`;
}

// ── write / check ────────────────────────────────────────────────────────────────────────────
const outputs = [
  [V2_OUT, scopedV2()],
  [V2_SHELL_OUT, shellAdditiveV2()],
  [HUD_OUT, hudModule()],
];
let drift = 0;
for (const [rel, text] of outputs) {
  const p = join(ROOT, rel);
  let cur = null;
  try {
    cur = readFileSync(p, 'utf8');
  } catch {
    /* missing */
  }
  if (CHECK) {
    if (cur !== text) {
      drift++;
      console.error(`[gen-tokens] DRIFT: ${rel} is stale — run: node scripts/gen-tokens.mjs`);
    }
  } else if (cur !== text) {
    writeFileSync(p, text);
    console.log(`[gen-tokens] wrote ${rel}`);
  }
}
if (CHECK) {
  if (drift) process.exit(1);
  console.log('[gen-tokens] in sync');
}
