function blockOf(src, opener) {
  const at = src.indexOf(opener);
  if (at < 0) throw new Error(`${HUD_SOURCE_DS}: block "${opener}" not found`);
  return src.slice(at, src.indexOf('\n}', at));
}
function hudCss() {
  const src = ds(HUD_SOURCE_DS);
  const blocks = Object.fromEntries(
    Object.entries(HUD_BLOCKS).map(([t, o]) => [t, blockOf(src, o)])
  );
  // The HUD block is a literal snapshot (the canvas iframe may host another system), so a value
  // that is exactly `var(--other)` in the same block — a schema-v1 alias such as
  // `--canvas-dot: var(--x-canvas-dot)` — is followed to its declared value.
  const lookup = (theme, name, depth = 0) => {
    const m = blocks[theme].match(new RegExp(`^\\s*--${name}:\\s*([^;]+);`, 'm'));
    if (!m) throw new Error(`${HUD_SOURCE_DS} ${theme}: no --${name}`);
    const v = m[1].trim();
    const ref = /^var\(--([a-z0-9-]+)\)$/.exec(v);
    return ref && depth < 8 && new RegExp(`^\\s*--${ref[1]}:`, 'm').test(blocks[theme])
      ? lookup(theme, ref[1], depth + 1)
      : v;
  };
  const guide = (name) => {
    const m = ds(HUD_GUIDE_DS).match(new RegExp(`^\\s*--${name}:\\s*([^;]+);`, 'm'));
    if (!m) throw new Error(`${HUD_GUIDE_DS}: no --${name}`);
    return m[1].trim();
  };
  return HUD_TEMPLATE.replace(/\{guide:([a-z0-9-]+)\}/g, (_, name) => guide(name)).replace(
    /\{(dark|light):([a-z0-9-]+)\}/g,
    (_, theme, name) => lookup(theme, name)
  );
}
function hudModule() {
  return `// GENERATED by scripts/gen-tokens.mjs from .design/system/${HUD_SOURCE_DS}/colors_and_type.css
// — DO NOT EDIT BY HAND. Run: node scripts/gen-tokens.mjs
// The canvas iframe's HUD/chrome token block (--maude-hud-*, --maude-chrome-*), injected by
// canvas-shell.tsx. See the comment above its import there for why the HUD owns its own family.
export const HUD_TOKENS_CSS = \`${hudCss()}\`;
`;
}

// ── 3 · the native tab strip (apps/desktop/src/strip.html) ──────────────────────────────────────
// The strip is an app-local page (no studio CSS); it follows the OS appearance. Its accent, AI spark, status dot and
// project squares are the maude-v2 values, written between the page's gen-tokens markers. Its neutral greys stay the
// strip's own (native title-bar chrome, not a DS surface).
const STRIP_OUT = 'apps/desktop/src/strip.html';
const STRIP_NAMES = [
  '--accent',
  '--accent-soft',
  '--focus-ring',
  '--x-spark',
  '--spark',
  '--status-success',
  '--palette-1',
  '--object-yellow',
  '--palette-2',
  '--object-green',
  '--palette-3',
  '--object-lilac',
  '--palette-4',
  '--object-coral',
  '--palette-5',
  '--object-sky',
  '--palette-6',
  '--object-grey',
  '--palette-ink',
  '--object-ink',
];
function stripPage() {
  const b = v2Blocks();
  const pick = (lines, pad) =>
    STRIP_NAMES.map((n) => {
      const l = lines.find((x) => x.startsWith(`${n}:`));
      if (!l) throw new Error(`maude-v2: no ${n}`);
      return `${pad}${l.replace(/\s+/g, ' ')}`;
    }).join('\n');
  const block = `/* gen-tokens:begin — GENERATED by scripts/gen-tokens.mjs from maude-v2 (P8 C0); DO NOT EDIT BY HAND */
      :root {
${pick(b.light, '        ')}
      }
      @media (prefers-color-scheme: dark) {
        :root {
${pick(b.dark, '          ')}
        }
      }
      /* gen-tokens:end */`;
  const cur = readFileSync(join(ROOT, STRIP_OUT), 'utf8');
  const a = cur.indexOf('/* gen-tokens:begin');
  const z = cur.indexOf('/* gen-tokens:end */');
  if (a < 0 || z < a) throw new Error(`${STRIP_OUT}: gen-tokens markers missing`);
  return cur.slice(0, a) + block + cur.slice(z + '/* gen-tokens:end */'.length);
}

