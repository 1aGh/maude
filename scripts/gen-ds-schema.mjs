#!/usr/bin/env node
// Generated artefacts of the design-system schema registry (V2-1.13 §5.1, §5.5).
//
//   node scripts/gen-ds-schema.mjs           write them
//   node scripts/gen-ds-schema.mjs --check   exit 1 on drift
//
// 1. apps/studio/schema/ds-schema-v1.fallbacks.css — renderFallbacks(registry): the full layer.
// 2. the structural class contract + .t-* type roles in core/preview/_components.css.tpl, between
//    its `ds-schema:components` markers — the same `components.core[].fallbackCss` text, so
//    templates and fallbacks never drift (E3);
// 3. the README template's "## Token usage guide" from the registry's role meanings;
// 4. core/components.json.tpl — the core components mapped to those contract classes.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FALLBACKS_HEADER, renderFallbacks } from '../apps/studio/ds/fallbacks.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const reg = JSON.parse(readFileSync(join(ROOT, 'apps/studio/schema/ds-schema-v1.json'), 'utf8'));

const outputs = [];
outputs.push({
  rel: 'apps/studio/schema/ds-schema-v1.fallbacks.css',
  text: FALLBACKS_HEADER + renderFallbacks(reg),
});

const CORE = 'plugins/design/templates/design-system-inspiration/core';
const read = (rel) => {
  try {
    return readFileSync(join(ROOT, rel), 'utf8');
  } catch {
    return null;
  }
};
/** Replace the text between two markers (both kept). Throws when the markers are out of order. */
function between(rel, begin, end, block) {
  const tpl = read(rel);
  if (!tpl?.includes(begin)) return;
  const a = tpl.indexOf(begin);
  const b = tpl.indexOf(end);
  if (b < a) throw new Error(`${rel}: ds-schema markers out of order`);
  outputs.push({ rel, text: `${tpl.slice(0, a)}${begin}\n${block}\n${tpl.slice(b)}` });
}

// 2 · the structural class contract + `.t-*` type roles, in _components.css.tpl
const typeRoleCss = reg.typeRoles
  .filter((t) => t.required)
  .map(
    (t) =>
      `.${t.class} { ${Object.entries(t.fallback)
        .map(([p, v]) => `${p}: ${v};`)
        .join(' ')} }`
  )
  .join('\n');
between(
  `${CORE}/preview/_components.css.tpl`,
  '/* ds-schema:components:begin — GENERATED by scripts/gen-ds-schema.mjs, do not edit */',
  '/* ds-schema:components:end */',
  [
    ...reg.components.core
      .filter((c) => c.fallbackCss)
      .map((c) => `/* ${c.name} */\n${c.fallbackCss}`),
    `/* Type roles (<Text role>) */\n${typeRoleCss}`,
  ].join('\n\n')
);

// 3 · README "## Token usage guide" from the registry meanings (keeper Pass B reads it)
const groups = new Map();
for (const r of reg.roles) {
  const g = groups.get(r.group) ?? [];
  g.push(`| \`${r.name}\` | ${r.meaning} |`);
  groups.set(r.group, g);
}
between(
  `${CORE}/README.philosophy.md.tpl`,
  '<!-- ds-schema:token-guide:begin — GENERATED by scripts/gen-ds-schema.mjs from the schema registry, do not edit -->',
  '<!-- ds-schema:token-guide:end -->',
  [
    'One token, one job. A canvas uses these names only — never a literal colour, size or font.',
    '',
    '| Token | Use it for |',
    '| --- | --- |',
    ...[...groups.values()].flat(),
  ].join('\n')
);

// 4 · components.json.tpl — the core components mapped to the contract classes above
const components = {};
for (const c of reg.components.core) {
  const own = (c.alsoClasses ?? []).filter((x) => x.startsWith(`${c.class}--`));
  const css = c.fallbackCss ?? '';
  const has = (cls) =>
    new RegExp(`\\.${cls}(?![\\w-])`).test(css) ||
    new RegExp(`\\.${cls}(?![\\w-])`).test(
      reg.components.core.find((x) => x.class === c.class)?.fallbackCss ?? ''
    );
  const entry = { class: [c.class, ...own].join(' '), export: c.export };
  if (c.variants?.length)
    entry.variants = Object.fromEntries(
      c.variants.map((v) => [v, has(`${c.class}--${v}`) ? `${c.class}--${v}` : null])
    );
  if (c.sizes?.length)
    entry.sizes = Object.fromEntries(
      c.sizes.map((s) => [s, has(`${c.class}--${s}`) ? `${c.class}--${s}` : null])
    );
  components[c.name] = entry;
}
const componentsTpl = JSON.stringify(
  {
    $schema:
      'https://raw.githubusercontent.com/1aGh/maude/main/apps/studio/schema/ds-components-v1.schema.json',
    schemaVersion: 1,
    system: '{{ds_dirname}}',
    components,
    typeRoles: Object.fromEntries(
      reg.typeRoles.filter((t) => t.required).map((t) => [t.role, t.class])
    ),
    icons: { family: '{{ds_dirname}}', map: '{{icon_map_json}}' },
  },
  null,
  2
).replace('"{{icon_map_json}}"', '{{icon_map_json}}');
outputs.push({ rel: `${CORE}/components.json.tpl`, text: `${componentsTpl}\n` });

let drift = 0;
for (const o of outputs) {
  const p = join(ROOT, o.rel);
  let cur = null;
  try {
    cur = readFileSync(p, 'utf8');
  } catch {}
  if (cur === o.text) continue;
  if (CHECK) {
    console.error(`gen-ds-schema: ${o.rel} is stale — run: node scripts/gen-ds-schema.mjs`);
    drift++;
  } else {
    writeFileSync(p, o.text);
    console.log(`wrote ${o.rel}`);
  }
}
process.exit(drift ? 1 : 0);
