// S8.23 — the page side of the desktop export doors (Save to, Show in Finder, Copy as PNG). Rust is the
// gate (export_save.rs, cargo tests); here: the command names match what the shell registers and grants,
// the args match the Rust signature, a browser tab downloads instead, and Copy as PNG falls back to the
// shell only when the browser clipboard refuses — sending raw bytes, never a JSON array.
import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  looksLikePng,
  MAX_CLIPBOARD_PNG,
  nativeSave,
  SAVE_COMMANDS,
  SAVE_TO,
} from '../client/v2/export/native-save.js';

const TAURI = join(import.meta.dir, '../../desktop/src-tauri');
const read = (p: string) => readFileSync(join(TAURI, p), 'utf8');

function recorder(answer: (cmd: string, args: unknown) => unknown = () => null) {
  const calls: [string, unknown][] = [];
  const invoke = async (cmd: string, args: unknown) => {
    calls.push([cmd, args]);
    return answer(cmd, args);
  };
  return { calls, invoke };
}

const PNG = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13]);

describe('native save (S8.23)', () => {
  test('every command is registered, granted to project tabs and caller-checked in Rust', () => {
    const lib = read('src/lib.rs');
    const grants = JSON.parse(read('capabilities/default.json')).permissions as string[];
    const src = read('src/export_save.rs');
    for (const cmd of Object.values(SAVE_COMMANDS)) {
      expect(lib).toContain(`export_save::${cmd},`);
      expect(grants).toContain(`allow-${cmd.replace(/_/g, '-')}`);
      expect(read(`permissions/autogenerated/${cmd}.toml`)).toContain(
        `commands.allow = ["${cmd}"]`
      );
      expect(src).toMatch(new RegExp(`pub (async )?fn ${cmd}\\(`));
    }
    // saveTo values and the clipboard cap are the Rust ones.
    for (const v of SAVE_TO) expect(src).toContain(`Some("${v}")`);
    expect(src).toContain('pub const MAX_CLIPBOARD_PNG: usize = 64 * 1024 * 1024;');
    expect(MAX_CLIPBOARD_PNG).toBe(64 * 1024 * 1024);
  });

  test('save sends jobId + filename (+ saveTo) and returns the path Rust wrote', async () => {
    const r = recorder(() => '/Users/x/Downloads/social/Hero.png');
    const doors = nativeSave(null, { invoke: r.invoke });
    expect(doors.available).toBe(true);
    expect(
      await doors.save({ jobId: 'a1-b2', filename: 'Hero.png', saveTo: 'remembered' })
    ).toEqual({
      ok: true,
      path: '/Users/x/Downloads/social/Hero.png',
    });
    expect(await doors.save({ jobId: 'a1-b2', filename: 'Hero.png' })).toMatchObject({ ok: true });
    expect(r.calls).toEqual([
      ['save_export', { jobId: 'a1-b2', filename: 'Hero.png', saveTo: 'remembered' }],
      ['save_export', { jobId: 'a1-b2', filename: 'Hero.png' }],
    ]);
  });

  test('a cancelled panel, a refusal and a bad id or saveTo never claim a save', async () => {
    const cancel = nativeSave(null, { invoke: recorder(() => null).invoke });
    expect(await cancel.save({ jobId: 'a', filename: 'x' })).toEqual({
      ok: false,
      reason: 'cancelled',
    });
    const refuse = nativeSave(null, {
      invoke: async () => {
        throw 'Switch to this tab first.';
      },
    });
    expect(await refuse.save({ jobId: 'a', filename: 'x' })).toEqual({
      ok: false,
      reason: 'refused',
      error: 'Switch to this tab first.',
    });
    const r = recorder();
    const doors = nativeSave(null, { invoke: r.invoke });
    for (const jobId of ['', 'a/../b', 'x?y', 'a'.repeat(65)]) {
      expect((await doors.save({ jobId, filename: 'x' })).ok).toBe(false);
    }
    expect((await doors.save({ jobId: 'a', filename: 'x', saveTo: '/etc' as never })).ok).toBe(
      false
    );
    expect(r.calls).toEqual([]);
  });

  test('a browser tab downloads the job instead and has no Show in Finder', async () => {
    const got: unknown[] = [];
    const doors = nativeSave(null, {
      download: async (id: string, name: string) => void got.push([id, name]),
    });
    expect(doors.available).toBe(false);
    expect(await doors.save({ jobId: 'j1', filename: 'a.pdf', saveTo: 'downloads' })).toEqual({
      ok: true,
      path: null,
      downloaded: true,
    });
    expect(got).toEqual([['j1', 'a.pdf']]);
    expect(await doors.reveal('/Users/x/a.pdf')).toEqual({ ok: false, reason: 'browser' });
  });

  test('reveal passes the path back as Rust returned it and carries its refusal', async () => {
    const r = recorder((_c, a) => {
      if ((a as { path: string }).path !== '/Users/x/out.png') throw "Maude didn't save that file.";
      return null;
    });
    const doors = nativeSave(null, { invoke: r.invoke });
    expect(await doors.reveal('/Users/x/out.png')).toEqual({ ok: true });
    expect(await doors.reveal('/etc/hosts')).toEqual({
      ok: false,
      reason: 'refused',
      error: "Maude didn't save that file.",
    });
    expect((await doors.reveal('')).ok).toBe(false);
    expect(r.calls).toEqual([
      ['reveal_export', { path: '/Users/x/out.png' }],
      ['reveal_export', { path: '/etc/hosts' }],
    ]);
  });

  test('Copy as PNG: the browser clipboard first, the shell only when it refuses — raw bytes', async () => {
    class Item {
      constructor(public data: Record<string, Blob>) {}
    }
    const written: unknown[] = [];
    const ok = nativeSave(null, {
      invoke: recorder().invoke,
      clipboard: { write: async (items: unknown[]) => void written.push(items) },
      ClipboardItem: Item,
    });
    expect(await ok.copyPng(new Blob([PNG], { type: 'image/png' }))).toEqual({
      ok: true,
      via: 'browser',
    });
    expect(written.length).toBe(1);

    const r = recorder();
    const refusing = nativeSave(null, {
      invoke: r.invoke,
      clipboard: {
        write: async () => {
          throw new Error('NotAllowedError');
        },
      },
      ClipboardItem: Item,
    });
    expect(await refusing.copyPng(new Blob([PNG], { type: 'image/png' }))).toEqual({
      ok: true,
      via: 'shell',
    });
    expect(r.calls.length).toBe(1);
    expect(r.calls[0][0]).toBe('clipboard_write_png');
    expect(r.calls[0][1]).toBeInstanceOf(Uint8Array);
    expect(Array.from(r.calls[0][1] as Uint8Array)).toEqual(Array.from(PNG));
  });

  test('Copy as PNG never sends a non-PNG or an oversized image to the shell', async () => {
    const r = recorder();
    const doors = nativeSave(null, { invoke: r.invoke, clipboard: null, ClipboardItem: null });
    expect(await doors.copyPng(new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 0, 0, 0, 0, 0]))).toEqual({
      ok: false,
      reason: 'refused',
      error: "That isn't a PNG image.",
    });
    const big = new Uint8Array(MAX_CLIPBOARD_PNG + 1);
    big.set(PNG);
    expect((await doors.copyPng(big)).error).toBe(
      'That image is too big to copy. Export it instead.'
    );
    expect(r.calls).toEqual([]);
    expect(looksLikePng(PNG)).toBe(true);
    expect(looksLikePng(new Uint8Array(4))).toBe(false);
  });
});
