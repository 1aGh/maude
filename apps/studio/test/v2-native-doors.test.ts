// S11.16 — the page side of the native doors (Reveal in Finder, Open in editor, Show logs in Finder)
// and the crash notice. Rust is the gate (doors.rs / lifecycle.rs, cargo tests); here: the command
// names match what the shell registers and grants, a path the shell would refuse never leaves the
// page, a browser tab asks nobody, and the crash notice is asked for once.
import { afterEach, describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ACTIONS_BY_ID } from '../actions/index.ts';
import {
  CRASHED_KIND,
  DOOR_COMMANDS,
  isProjectRel,
  nativeDoors,
  onCrashed,
  projectRel,
  resetCrashNoticeForTest,
} from '../client/v2/shell/native-doors.js';

const TAURI = join(import.meta.dir, '../../desktop/src-tauri');
const read = (p: string) => readFileSync(join(TAURI, p), 'utf8');

function recorder(answer: (cmd: string, args: unknown) => unknown = () => null) {
  const calls: [string, unknown][] = [];
  const invoke = async (cmd: string, args: unknown) => {
    calls.push([cmd, args]);
    return answer(cmd, args);
  };
  return { calls, invoke };
}

afterEach(() => resetCrashNoticeForTest());

describe('native doors (S11.16)', () => {
  test('every door is a command the shell registers, grants to project tabs and caller-checks', () => {
    const lib = read('src/lib.rs');
    const grants = JSON.parse(read('capabilities/default.json')).permissions as string[];
    for (const cmd of [...Object.values(DOOR_COMMANDS), 'take_crash_notice']) {
      expect(lib).toMatch(new RegExp(`(doors|lifecycle)::${cmd},`));
      expect(grants).toContain(`allow-${cmd.replace(/_/g, '-')}`);
      expect(read(`permissions/autogenerated/${cmd}.toml`)).toContain(
        `commands.allow = ["${cmd}"]`
      );
    }
    // Never on Home or the strip.
    const home = read('src/home.rs');
    const strip = read('capabilities/strip.json');
    for (const cmd of Object.values(DOOR_COMMANDS)) {
      expect(home.includes(`allow-${cmd.replace(/_/g, '-')}`)).toBe(false);
      expect(strip.includes(cmd.replace(/_/g, '-'))).toBe(false);
    }
  });

  test('a registry id a door runs is exec native and desktop-only where it exists', () => {
    for (const id of Object.keys(DOOR_COMMANDS)) {
      const def = (ACTIONS_BY_ID as Record<string, { exec?: string }>)[id];
      if (def) expect(def.exec).toBe('native');
    }
  });

  test('only a project-relative path leaves the page', () => {
    for (const ok of ['.design/ui/Pricing.tsx', 'ui/a b.tsx', './x.tsx', '.design/ui']) {
      expect(isProjectRel(ok)).toBe(true);
    }
    for (const bad of [
      '',
      '/etc/hosts',
      '\\\\srv\\x',
      'C:\\x',
      '../outside',
      '.design/../../x',
      'a\\..\\b',
      'a\0b',
      null,
      42,
    ]) {
      expect(isProjectRel(bad as unknown as string)).toBe(false);
    }
    expect(projectRel('.design', 'ui/Pricing.tsx')).toBe('.design/ui/Pricing.tsx');
    expect(projectRel('/.design/', '/ui/Pricing.tsx')).toBe('.design/ui/Pricing.tsx');
    expect(projectRel('', 'ui/Pricing.tsx')).toBe('ui/Pricing.tsx');
  });

  test('the doors call the shell with the rel only; a refused path never asks it', async () => {
    const r = recorder();
    const d = nativeDoors(null, { invoke: r.invoke });
    expect(d.available).toBe(true);
    expect(await d.revealPath('.design/ui/a.tsx')).toEqual({ ok: true });
    expect(await d.openInEditor('.design/ui/a.tsx')).toEqual({ ok: true });
    expect(await d.revealLogs()).toEqual({ ok: true });
    expect(await d.run('canvas.open-in-editor', '.design/ui/b.tsx')).toEqual({ ok: true });
    expect(r.calls).toEqual([
      ['project_reveal_path', { rel: '.design/ui/a.tsx' }],
      ['project_open_in_editor', { rel: '.design/ui/a.tsx' }],
      ['diagnostics_reveal_logs', {}],
      ['project_open_in_editor', { rel: '.design/ui/b.tsx' }],
    ]);
    const refused = await d.revealPath('../secret');
    expect(refused).toEqual({
      ok: false,
      reason: 'refused',
      error: "That file isn't in this project.",
    });
    expect(r.calls.length).toBe(4);
  });

  test("the shell's refusal comes back in its own words", async () => {
    const d = nativeDoors(null, {
      invoke: async () => {
        throw 'Switch to this tab first.';
      },
    });
    expect(await d.revealPath('.design/ui/a.tsx')).toEqual({
      ok: false,
      reason: 'refused',
      error: 'Switch to this tab first.',
    });
    // The Rust answers the page shows, pinned against doors.rs.
    const doors = read('src/doors.rs');
    expect(doors).toContain(`"That file isn't in this project."`);
  });

  test('a browser tab asks nobody', async () => {
    const d = nativeDoors({} as Window);
    expect(d.available).toBe(false);
    expect(await d.revealPath('.design/ui/a.tsx')).toEqual({ ok: false, reason: 'browser' });
    expect(await d.openInEditor('../x')).toEqual({ ok: false, reason: 'browser' });
    expect(await d.revealLogs()).toEqual({ ok: false, reason: 'browser' });
    expect(await d.takeCrashNotice()).toBe(null);
  });

  test('app://crashed is asked for once per page and handed to every listener', async () => {
    const notice = { kind: CRASHED_KIND, startedAt: 1_700_000_000_000 };
    const r = recorder((cmd) => (cmd === 'take_crash_notice' ? notice : null));
    const heard: unknown[] = [];
    expect(await onCrashed((n) => heard.push(n), null, { invoke: r.invoke })).toEqual(notice);
    expect(await onCrashed((n) => heard.push(n), null, { invoke: r.invoke })).toEqual(notice);
    expect(r.calls).toEqual([['take_crash_notice', {}]]);
    expect(heard).toEqual([notice, notice]);
    // A clean last run: nothing parked, nothing heard.
    resetCrashNoticeForTest();
    const quiet = recorder(() => null);
    const none: unknown[] = [];
    expect(await onCrashed((n) => none.push(n), null, { invoke: quiet.invoke })).toBe(null);
    expect(none).toEqual([]);
    // A refused take (off its origin) is no notice, not an error.
    resetCrashNoticeForTest();
    const no = await onCrashed(() => {}, null, {
      invoke: async () => {
        throw 'This window isn\u2019t showing its project.';
      },
    });
    expect(no).toBe(null);
    expect(read('src/lifecycle.rs')).toContain(`pub const CRASHED_KIND: &str = "${CRASHED_KIND}";`);
  });
});
