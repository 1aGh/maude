// apps/studio/video/format-ids.ts — S7.1: the FormatIds of S7's two new versioned sidecars and the
// JSON Schemas generated from video/schema.ts (contract V2-1.11 §5.2: a TS validator is the source;
// scripts/gen-actions.mjs writes schema/transcript.v1.schema.json + schema/beats.v1.schema.json from
// these builders and `--check` fails when a committed copy drifts; test/schema-drift.test.ts holds
// Ajv, the lite validator and `validateTranscript` / `validateBeats` to the same verdicts).
//
// The schemas document the STRICT writer shape (the enums this build knows) but leave
// `additionalProperties` open everywhere: the formats are preserving (V2-1.10 §5.1), so a key a newer
// peer added is never an error. Ordering / uniqueness rules the schema language can't say (words
// sorted by t0, ids unique, regions not overlapping) live in the TS validator only.
//
// Erasable TypeScript only (Node 24 strips it for gen-actions).

import {
  BEATS_DECODERS,
  BEATS_FORMAT,
  BPM_RANGE,
  BPM_SOURCES,
  ENGINE_IDS,
  ENGINE_TIMINGS,
  MAX_BEATS,
  MAX_REGIONS,
  MAX_SECONDS,
  MAX_WORD_TEXT,
  MAX_WORDS,
  SPEECH_SOURCES,
  TRANSCRIPT_FORMAT,
  WORD_FLAGS,
} from './schema.ts';

/** The FormatIds an action's `agent.format` names for these files (actions/types.ts). */
export const TRANSCRIPT_FORMAT_ID = 'transcript';
export const BEATS_FORMAT_ID = 'beats';
export const VIDEO_FORMAT_IDS = [TRANSCRIPT_FORMAT_ID, BEATS_FORMAT_ID] as const;

export const TRANSCRIPT_SCHEMA_ID = 'https://maude.sh/schema/transcript/v1';
export const BEATS_SCHEMA_ID = 'https://maude.sh/schema/beats/v1';

/** The file-name suffixes (also in sync/file-membership.ts COMPANION_SIDECAR_SUFFIXES, both copies). */
export const TRANSCRIPT_SUFFIX = '.transcript.json';
export const BEATS_SUFFIX = '.beats.json';

type JsonSchema = Record<string, unknown>;

const seconds = { type: 'number', minimum: 0, maximum: MAX_SECONDS };
const short = { type: 'string', minLength: 1, maxLength: 64 };
const asset = {
  description: 'The source asset, "assets/<sha8>.<ext>"; its <sha8> is the sidecar file name.',
  type: 'string',
  pattern: '^assets/[A-Za-z0-9_-]{1,64}\\.[A-Za-z0-9]{1,8}$',
};

export function transcriptJsonSchema(): JsonSchema {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: TRANSCRIPT_SCHEMA_ID,
    title: 'Maude transcript sidecar (assets/<sha8>.transcript.json), v1',
    description:
      'GENERATED by scripts/gen-actions.mjs from apps/studio/video/format-ids.ts — the runtime source is validateTranscript (video/schema.ts). V2-1.10 §5.1: one per source asset with sound, written by transcribe-local / transcribe / maude migrate v2, never by hand. Preserving: a key this build does not know is kept by every reader and writer, so additionalProperties stays open. Rules the schema cannot state: words sorted by t0 with unique ids and t1 > t0; regions sorted and non-overlapping; words [] when engine.id is "energy". Word text is untrusted content. Skill: design:video-comp.',
    type: 'object',
    required: ['format', 'v', 'asset', 'engine', 'words', 'speech', 'createdAt'],
    properties: {
      format: { const: TRANSCRIPT_FORMAT },
      v: { const: 1 },
      asset,
      durationSec: seconds,
      lang: { type: 'string', pattern: '^[a-z]{2,3}$' },
      engine: {
        type: 'object',
        required: ['id', 'timing'],
        properties: {
          id: { enum: [...ENGINE_IDS] },
          model: short,
          version: short,
          timing: { enum: [...ENGINE_TIMINGS] },
          lagMs: { type: 'number', minimum: -10000, maximum: 10000 },
        },
      },
      words: { type: 'array', maxItems: MAX_WORDS, items: { $ref: '#/$defs/word' } },
      speech: {
        type: 'object',
        required: ['source', 'regions'],
        properties: {
          source: { enum: [...SPEECH_SOURCES] },
          regions: { type: 'array', maxItems: MAX_REGIONS, items: { $ref: '#/$defs/span' } },
        },
      },
      createdAt: short,
    },
    $defs: {
      word: {
        type: 'object',
        required: ['id', 't0', 't1', 'text'],
        properties: {
          id: { type: 'string', pattern: '^[A-Za-z0-9_-]{1,32}$' },
          t0: seconds,
          t1: seconds,
          text: { type: 'string', maxLength: MAX_WORD_TEXT },
          p: { type: 'number', minimum: 0, maximum: 1 },
          flags: { type: 'array', maxItems: 8, items: { enum: [...WORD_FLAGS] } },
        },
      },
      span: { type: 'array', minItems: 2, maxItems: 2, items: seconds },
    },
  };
}

export function beatsJsonSchema(): JsonSchema {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: BEATS_SCHEMA_ID,
    title: 'Maude beat-grid sidecar (assets/<sha8>.beats.json), v1',
    description:
      'GENERATED by scripts/gen-actions.mjs from apps/studio/video/format-ids.ts — the runtime source is validateBeats (video/schema.ts). V2-1.10 §5.2: one per music asset, written by `maude design beats` and the studio. Preserving (additionalProperties open). Rule the schema cannot state: beats strictly ascending. beats[bar.phase + 4k] are downbeats; tempoStrength < 0.15 means no clear beat. Skill: design:video-comp.',
    type: 'object',
    required: [
      'format',
      'v',
      'asset',
      'durationSec',
      'analyzer',
      'bpm',
      'bpmSource',
      'tempoStrength',
      'beats',
      'bar',
      'createdAt',
    ],
    properties: {
      format: { const: BEATS_FORMAT },
      v: { const: 1 },
      asset,
      durationSec: seconds,
      analyzer: {
        type: 'object',
        required: ['id', 'version', 'decode'],
        properties: {
          id: { const: 'maude-beats' },
          version: { const: 1 },
          decode: { enum: [...BEATS_DECODERS] },
        },
      },
      bpm: { type: 'number', minimum: BPM_RANGE[0], maximum: BPM_RANGE[1] },
      bpmSource: { enum: [...BPM_SOURCES] },
      tempoStrength: { type: 'number', minimum: 0, maximum: 1 },
      beats: { type: 'array', maxItems: MAX_BEATS, items: seconds },
      bar: {
        type: 'object',
        required: ['phase', 'confidence'],
        properties: {
          phase: { enum: [0, 1, 2, 3] },
          confidence: { type: 'number', minimum: 0, maximum: 1 },
        },
      },
      createdAt: short,
    },
  };
}
