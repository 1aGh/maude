import { mkdirSync } from 'node:fs';
import { boot, openPage, scratchProject, sleep, REPO } from './lib.mjs';
import { base } from './fx.mjs';
const theme = process.argv[2] || 'light';
const src = await base();
const { scratch, project } = scratchProject(src);
const s = await boot(project, scratch, {}, { theme });
const { browser, page } = await openPage(s.url, { theme });
await sleep(3500);
const x = page.locator('[data-testid^="notice-whats-new"] .maude-notice-close').first();
if (await x.count()) await x.click().catch(() => {});
await sleep(500);
await sleep(Number(process.env.WAIT || 500));
mkdirSync(`${REPO}/.scr/dev`, { recursive: true });
await page.screenshot({ path: `${REPO}/.scr/dev/panel-${theme}.png`, clip: { x: 0, y: 0, width: 520, height: 800 } });
console.log(await page.locator('.cv-panel').first().evaluate((e) => e.parentElement.outerHTML.slice(0, 2500)).catch((e) => String(e)));
await browser.close();
s.stop();
process.exit(0);
