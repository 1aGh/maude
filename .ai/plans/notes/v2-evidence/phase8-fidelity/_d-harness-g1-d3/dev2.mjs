// dev loop for the comment surfaces: Preview + Comment tool on the 04 fixture's Homepage
import { mkdirSync } from 'node:fs';
import { boot, openPage, scratchProject, sleep, REPO } from './lib.mjs';
import { studio } from './fx4.mjs';
const theme = process.argv[2] || 'light';
const src = await studio();
const { scratch, project } = scratchProject(src);
const s = await boot(project, scratch, {}, { theme, whatsNewSeen: '99.0.0' });
const { browser, page, logs } = await openPage(s.url, { theme, w: 1440, h: 900 });
await sleep(3500);
const x = page.locator('[data-testid^="notice-whats-new"] .maude-notice-close').first();
if (await x.count()) await x.click().catch(() => {});
const out = `${REPO}/.scr/dev`;
mkdirSync(out, { recursive: true });
const f = page.frameLocator('[data-testid="canvas-frame"]');
const el = (id) => f.locator(`[data-cd-id="${id}"]`).first();
await page.locator('[data-testid="canvas-row-ui-homepage"]').first().click();
await sleep(4000);
await page.locator('[data-testid="palette-mode-preview"]').click();
await sleep(1800);
await page.screenshot({ path: `${out}/c0-preview-${theme}.png` });
await f.locator('[data-testid="toolbar-slot-comment"]').first().click({ timeout: 4000 });
await sleep(1200);
await page.screenshot({ path: `${out}/c1-armed-${theme}.png` });
await el('tablet-h1').click({ timeout: 4000 });
await sleep(900);
await page.keyboard.type('Cards on tablet — tighten the gap @');
await sleep(800);
await page.screenshot({ path: `${out}/c2-composer-${theme}.png` });
await page.keyboard.press('Backspace');
await page.keyboard.press('Meta+Enter');
await sleep(1500);
await page.screenshot({ path: `${out}/c3-thread-${theme}.png` });
await f.locator('.cm-pin').first().click({ timeout: 4000 });
await sleep(900);
await page.screenshot({ path: `${out}/c4-open-${theme}.png`, clip: { x: 380, y: 60, width: 760, height: 380 } });
await f.locator('.cm-thread__reply-textarea').first().click();
await page.keyboard.type('Agree. Then the -15 % moves onto Yearly. @Jo');
await sleep(900);
await page.screenshot({ path: `${out}/c5-reply-${theme}.png`, clip: { x: 380, y: 60, width: 760, height: 380 } });
console.log(logs.filter((l) => /pageerror/.test(l)).slice(0, 3).join('\n'));
await browser.close();
s.stop();
process.exit(0);
