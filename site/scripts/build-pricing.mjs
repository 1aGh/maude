#!/usr/bin/env node
// Mirror the Cloud price list into the site so no page ever types a price by hand.
// Vercel uploads only site/, so site/lib/pricing.json is COMMITTED (same rationale as
// stats.json / whats-new.json); apps/cloud/pricing.json is the single source and may be absent
// at deploy time, in which case the committed copy stays.
//
// Reads:   apps/cloud/pricing.json   (plans[].amounts, trialDays, currency, addons[].amounts)
// Output:  site/lib/pricing.json     { currency, taxBehavior, trialDays, plans, storage }
// Flags:   --check   exit 1 when the committed file is stale (quality.site-content gate)
//
// Amounts stay in minor units (cents). Stripe ids are deliberately NOT copied: nothing on the
// public site needs them.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const source = resolve(__dirname, '../../apps/cloud/pricing.json');
const out = resolve(__dirname, '../lib/pricing.json');
const check = process.argv.includes('--check');

if (!existsSync(source)) {
  console.log(
    '[pricing] apps/cloud/pricing.json not found, keeping the committed site/lib/pricing.json'
  );
  process.exit(0);
}

const src = JSON.parse(readFileSync(source, 'utf8'));
const plan = (id) => {
  const p = src.plans.find((x) => x.id === id);
  if (!p) throw new Error(`[pricing] plan "${id}" missing from apps/cloud/pricing.json`);
  return {
    name: p.name,
    includedStorageGb: p.includedStorageGb,
    monthlyMinor: p.amounts.monthlyMinor,
    annualMinor: p.amounts.annualMinor ?? null,
  };
};
const storage = src.addons.find((a) => a.id === 'storage');
if (!storage) throw new Error('[pricing] addon "storage" missing from apps/cloud/pricing.json');

const pricing = {
  // Generated by site/scripts/build-pricing.mjs from apps/cloud/pricing.json. Do NOT edit by hand.
  currency: src.currency,
  taxBehavior: src.taxBehavior,
  trialDays: src.trialDays,
  plans: { project: plan('project'), dedicated: plan('dedicated') },
  storage: { blockGb: storage.blockGb, monthlyMinor: storage.amounts.monthlyMinor },
};
const next = `${JSON.stringify(pricing, null, 2)}\n`;

if (check) {
  const have = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (have !== next) {
    console.error(
      '[pricing] site/lib/pricing.json is stale, run: pnpm --filter @maude/site gen:pricing'
    );
    process.exit(1);
  }
  console.log('[pricing] up to date');
} else {
  writeFileSync(out, next);
  console.log(`[pricing] wrote ${out}`);
}
